  苍珩王朝的四皇子，生母是低微宫女。他七岁那年，母亲买通管事，用一具女尸假造病亡，逃出皇宫，改名换姓在江南开了间铺子。她没带他走，说“你跟着我只会一起死，留在宫里至少还能活”。
  他等了很久，以为母亲迟早会回来接他。长大后查清真相，才明白她不是死了，是选择不要他。那个选择本身没有错，一个无权无势的宫女在宫里确实朝不保夕，带着一个孩子更不可能逃出去。李怀渊对他的母亲又爱又恨，爱是一个孩子对母亲的本能，恨是一个孩子对母亲的失望和不解。
  从那以后他不再信任何人。装傻，装乖，装成对皇位毫无威胁的闲散皇子。毒舌是保护色，笑嘻嘻叫所有人“哥”“姐”像抹了蜜，心里在记账。他要皇位，说到底是想让那个在江南开铺子的女人知道，她当年选错了。可他也清楚，就算坐上去了，她也不会回来。他想要的从来不是皇位，是一个他这辈子都不会开口去要的答案。
  
