  登基前夜。
  
  李怀渊已经布好了所有棋子。禁军被收买，朝中重臣被他捏住了把柄，诏书拟好了，传国玉玺也找到了。一切只等天亮，他一声令下，整个苍珩就要变天。
  
  但玩家从魏元璟那里拿到的提示是，李怀渊最近已经咳血了。他撑不到登基。他太虚弱，这几个月靠一股狠劲撑着，等那股劲泄了，人就没了。
  
  玩家必须在这个晚上做出选择。可以去人间见他，也可以不去。
  
  如果去，李怀渊坐在自己的旧院子里。不是宫殿，是他七岁那年母亲离开后，他一个人住了十几年的那个偏僻小院。他穿着登基用的龙袍，坐在院中，手里拿着半块饼，是小时候那种最便宜的饼。他看见玩家来了，笑了一下，说：“你来送行？”
  
  玩家和他对峙。李怀渊必须给出他为什么一定要皇位的真实答案。不是“报仇”，不是“报复”，是更私人的东西。玩家可以选择接受或者拒绝。
  
  接受——李怀渊第二天登基，玩家没再阻止。几年后他病逝，进归终殿。
  
  拒绝——玩家试图劝他放弃，告诉他皇位是牢笼。李怀渊会说“你又不是我，你怎么知道我要的不是牢笼”。如果玩家执意阻拦，李怀渊会翻脸，之后孤身行动，死亡，投胎。
  
  不去——李怀渊会派人给玩家送一样东西。可能是他小时候母亲留给他的唯一一件东西，比如一枚铜钱，或者半块玉佩。玩家收到东西的那天，李怀渊死了。
  
  这个节点的核心是：玩家必须面对“我到底能不能干涉一个人的人生”这个问题。李怀渊从来没有求过玩家救他。他只是用尽一切办法接近玩家，利用过，讨好过，最后真心过。但皇位是他自己的选择，玩家只能陪他走到这里。
  
  登基前夜的那半块饼，是他心里最软的地方，也是他唯一一次让人看到的破绽。
  
