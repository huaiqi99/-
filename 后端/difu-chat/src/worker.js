  export default {
    async fetch(request, env) {
      const corsHeaders = {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      };
  
      if (request.method === 'OPTIONS') {
        return new Response(null, { headers: corsHeaders });
      }
  
      if (request.method !== 'POST') {
        return new Response(
          JSON.stringify({ error: '传讯符 Worker 已启动 ✓ 但只接受 POST 请求(这是正常的)' }),
          { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
  
      try {
        const body = await request.json();
        const message = body.message || '';
        const profile = body.profile || 'linxiwu';
        const npcId = body.npcId || '';
        const history = Array.isArray(body.history) ? body.history : [];
  
        // 校验 npcId
        const systemPrompt = buildSystemPrompt(npcId, profile);
        if(!systemPrompt){
          return new Response(
            JSON.stringify({ error: '未知的 NPC ID: ' + npcId + '。支持的 NPC:luanfangqi, linhuai, luoxiu, weiyuanjing, chengmuqi, luojin, linxiwu' }),
            { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
          );
        }
  
          // ★ 修复:把 history 从 {side, sender, text} 转换成 {role, content}
        const aiHistoryFormatted = history.map(function(m){
          return {
            role: m.side === 'right' ? 'user' : 'assistant',
            content: m.text
          };
        });
  
        const messages = [
          { role: 'system', content: systemPrompt },
          ...aiHistoryFormatted.slice(-10),
          { role: 'user', content: message }
        ];
  
        // 调 DeepSeek
        const aiResponse = await fetch('https://api.deepseek.com/chat/completions', {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${env.DEEPSEEK_API_KEY}`
          },
          body: JSON.stringify({
            model: 'deepseek-chat',
            messages: messages,
            max_tokens: 400,
            temperature: 0.85  // 略高一点,让对话更自然有变化
          })
        });
  
        const aiData = await aiResponse.json();
  
        if (!aiData.choices || !aiData.choices[0]) {
          return new Response(
            JSON.stringify({ error: 'AI 返回异常: ' + JSON.stringify(aiData) }),
            { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
          );
        }
  
        const reply = aiData.choices[0].message.content;
  
        return new Response(
          JSON.stringify({ reply, npc: NPC_PROFILES[npcId].name }),
          { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
  
      } catch (error) {
        return new Response(
          JSON.stringify({ error: '服务器出错: ' + error.message }),
          { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
    }
  };
  