  function fieldLine(val){
    if(typeof val==='string') return val;
    if(Object.prototype.toString.call(val)==='[object Array]')
      return '\n- '+val.join('\n- ');
    if(val && typeof val==='object'){
      var parts=[];
      for(var k in val) if(Object.prototype.hasOwnProperty.call(val,k)) parts.push(k+'：'+val[k]);
      return '\n'+parts.join('\n');
    }
    return String(val);
  }
  
